/**
 * Professional franchise + home-venue dataset.
 *
 * These are stable facts (franchise name, home venue, venue coordinates, IANA
 * timezone), which is why they are checked in rather than fetched: they change
 * a few times a decade, and the geofence depends on the coordinates being right.
 * Schedules are the opposite — they change constantly and come from a licensed
 * provider at runtime. See server/src/jobs/proScheduleIngest.ts.
 *
 * Venue coordinates are the stadium/arena centroid. The posting geofence is 3km
 * (server/src/lib/geofencing.ts), which comfortably covers the bowl plus its
 * parking and tailgate footprint, so centroid precision is sufficient.
 *
 * `external_ref` is the stable identity key (`{league}:{slug}`). It must never
 * change once shipped — it is what lets a franchise survive a rename or
 * relocation while keeping its followers. When a team renames, change `name`
 * and leave `external_ref` alone.
 *
 * Trademark posture (see the design spec): names are plain text under nominative
 * fair use, no logos are stored or referenced, and no team gets a handle in the
 * @username namespace. `primary_color` is a single accent color for UI
 * legibility only.
 *
 * VERIFY-BEFORE-LAUNCH: entries flagged `// verify:` below are ones where the
 * venue changed recently or the franchise is newly added, and should be
 * confirmed against the schedule provider's venue feed before going live.
 * The ingester prefers the provider's per-fixture venue whenever it supplies
 * one, so a stale entry here degrades to a fallback rather than a wrong pin.
 */

